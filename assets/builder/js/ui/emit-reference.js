/**
 * "Tick this, get that" — every condition the builder offers, next to the Lua
 * it produces.
 *
 * Written by running each condition's own emitter with its default arguments,
 * so the table cannot drift from the generator the way a hand-written list
 * would. It answers the question the per-field hints are too small for: what
 * exactly is this going to put in my script?
 */

import { t } from '../core/i18n.js';
import { LuaWriter } from '../core/lua-writer.js';
import { CONDITION_KINDS, createLeaf, emitCondition } from '../domain/condition.js';
import { FARM_ACTIONS, HEAL_ACTIONS } from '../domain/config.js';
import { h } from './dom.js';

/**
 * @typedef {object} EmitSample
 * @property {string} group
 * @property {string} label
 * @property {string} lua
 */

/**
 * Every condition kind, rendered with its defaults.
 *
 * A kind whose emitter throws is reported rather than dropped: a broken sample
 * is a bug in that kind, and hiding it would hide the bug too.
 *
 * @returns {EmitSample[]}
 */
export function conditionSamples() {
  return Object.entries(CONDITION_KINDS).map(([kind, spec]) => {
    let lua;
    try {
      lua = emitCondition(withSampleValues(createLeaf(kind), spec), new LuaWriter());
    } catch (error) {
      lua = `-- ${error.message}`;
    }
    return { group: spec.group, label: spec.label, lua };
  });
}

/**
 * Fill the blank text fields with their own placeholders.
 *
 * A leaf built from defaults has empty names and empty phrases, and several
 * emitters answer an empty list with a bare `false` — correct, and useless as
 * an illustration. The placeholder is the example the field already suggests,
 * so the sample shows the shape a filled-in row produces.
 *
 * @param {import('../domain/condition.js').ConditionLeaf} leaf
 * @param {object} spec
 * @returns {import('../domain/condition.js').ConditionLeaf}
 */
function withSampleValues(leaf, spec) {
  for (const param of spec.params) {
    if (param.sample === false) continue;
    const current = leaf.params[param.key];
    const blank = current === '' || (Array.isArray(current) && !current.length);
    if (!blank || !param.placeholder) continue;
    leaf.params[param.key] = param.placeholder;
  }
  return leaf;
}

/**
 * The hunting and healing actions, which are one call each.
 *
 * @returns {EmitSample[]}
 */
export function actionSamples() {
  const samples = FARM_ACTIONS.map((action) => ({
    group: 'Where to hunt',
    label: action.label,
    lua: FARM_CALLS[action.id] ?? `${action.id}()`,
  }));
  for (const action of HEAL_ACTIONS) {
    samples.push({
      group: 'Where to hunt',
      label: action.label,
      lua: action.id === 'talkToNpcOnCell' ? 'talkToNpcOnCell(7, 9)' : 'usePokecenter()',
    });
  }
  return samples;
}

/**
 * The two farm actions that are not simply their own name.
 *
 * Fishing has no host call at all — it is a walk followed by a rod — and the
 * cell and item actions carry the argument the form asks for.
 */
const FARM_CALLS = Object.freeze({
  moveToCell: 'moveToCell(12, 30)',
  useItem: 'useItem("Repel")',
  fish: 'moveToCell(12, 30)  -- then, once standing there:\nuseItem("Super Rod")',
});

/**
 * The reference, as nodes ready to drop into the handbook.
 *
 * @returns {Node[]}
 */
export function renderEmitReference() {
  const samples = [...actionSamples(), ...conditionSamples()];
  /** @type {Map<string, EmitSample[]>} */
  const byGroup = new Map();
  for (const sample of samples) {
    if (!byGroup.has(sample.group)) byGroup.set(sample.group, []);
    byGroup.get(sample.group).push(sample);
  }

  return [
    h('h3.tool-subtitle', { text: t('Every choice, and what it writes') }),
    h('p.handbook-text', {
      text: t('Generated by running each check through the same emitter the script uses, '
        + 'with its arguments left at their defaults. Yours will carry the numbers and '
        + 'names you typed, but the shape is exactly this.'),
    }),
    ...[...byGroup].map(([group, rows]) => h('div.emit-group', {}, [
      h('h4.emit-group-title', { text: t(group) }),
      h('dl.emit-table', {}, rows.flatMap((row) => [
        h('dt.emit-label', { text: t(row.label) }),
        h('dd.emit-lua', {}, [h('code', { text: row.lua })]),
      ])),
    ])),
  ];
}
